import {createCipheriv, createDecipheriv, randomBytes} from 'node:crypto';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const DATA_SOURCE = '3d9b348a-4071-8079-9517-000b5ac5834f';
const API_VERSION = '2026-03-11';
const OUTPUT = new URL('./data.json', import.meta.url);

export function birthdayFromPage(page) {
  if (!page || page.object !== 'page' || page.archived || page.in_trash || page.is_archived) return null;
  const properties = page.properties || {};
  if (properties.Name?.type !== 'title' || properties.Date?.type !== 'date' || properties.Tags?.type !== 'multi_select') {
    throw new Error('My Calendar needs Name (title), Date (date), and Tags (multi-select) properties.');
  }
  if (!properties.Tags.multi_select.some(tag => tag.name === 'Birthday')) return null;
  const date = /^(\d{4})-(\d{2})-(\d{2})(?:$|T)/.exec(properties.Date.date?.start || '');
  if (!date) return null;
  const year = +date[1], month = +date[2], day = +date[3];
  if (year < 1000 || month < 1 || month > 12 || day < 1 || day > new Date(Date.UTC(year, month, 0)).getUTCDate()) return null;
  // Ignore the year: only month and day leave the runner, inside encrypted data.
  const title = properties.Name.title.map(part => part.plain_text ?? part.text?.content ?? '').join('').replace(/\s+/g, ' ').trim();
  const name = (title.replace(/^birthday\b[\s:—–-]*/i, '').replace(/(?:['’]s)?\s+birthday\s*$/i, '').trim() || title).slice(0, 180);
  return name ? {name, month, day} : null;
}
export function deduplicate(values) {
  const seen = new Set();
  return values.filter(Boolean).filter(entry => {
    const key = entry.name.normalize('NFKC').toLowerCase() + '|' + entry.month + '|' + entry.day;
    if (seen.has(key)) return false;
    seen.add(key); return true;
  }).sort((a,b) => a.month - b.month || a.day - b.day || a.name.localeCompare(b.name));
}
export function encrypt(payload, key) {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', key, iv);
  const encrypted = Buffer.concat([cipher.update(JSON.stringify(payload), 'utf8'), cipher.final(), cipher.getAuthTag()]);
  return {version:1, iv:iv.toString('base64'), data:encrypted.toString('base64')};
}
export function decrypt(feed, key) {
  const data = Buffer.from(feed.data, 'base64');
  const decipher = createDecipheriv('aes-256-gcm', key, Buffer.from(feed.iv, 'base64'));
  decipher.setAuthTag(data.subarray(-16));
  return JSON.parse(Buffer.concat([decipher.update(data.subarray(0,-16)), decipher.final()]).toString('utf8'));
}
export async function queryBirthdays(token, fetcher = fetch) {
  let cursor, values = [];
  for (let pageNumber = 0; pageNumber < 100; pageNumber++) {
    const body = {page_size:100, filter:{and:[
      {property:'Tags', multi_select:{contains:'Birthday'}},
      {property:'Date', date:{is_not_empty:true}}
    ]}};
    if (cursor) body.start_cursor = cursor;
    let response;
    for (let attempt = 0; attempt < 4; attempt++) {
      response = await fetcher('https://api.notion.com/v1/data_sources/' + DATA_SOURCE + '/query?filter_properties=Name&filter_properties=Date&filter_properties=Tags', {
        method:'POST', headers:{Authorization:'Bearer ' + token, 'Notion-Version':API_VERSION, 'Content-Type':'application/json'},
        body:JSON.stringify(body), signal:AbortSignal.timeout(30000)
      });
      if (response.status !== 429 && response.status < 500) break;
      if (attempt < 3) {
        const seconds = Math.max(1, Math.min(30, Number(response.headers.get('retry-after')) || 2 ** attempt));
        await new Promise(done => setTimeout(done, seconds * 1000));
      }
    }
    if (!response.ok) {
      const help = response.status === 401 ? 'Check NOTION_TOKEN.' : response.status === 403 || response.status === 404 ? 'Give your Notion integration access to My Calendar.' : response.status === 400 ? 'Check the Name, Date and Tags properties and the Birthday tag.' : 'Try Run workflow again later.';
      throw new Error('Notion returned HTTP ' + response.status + '. ' + help);
    }
    const data = await response.json();
    if (!Array.isArray(data.results)) throw new Error('Notion returned an unexpected response.');
    values.push(...data.results.map(birthdayFromPage));
    if (!data.has_more) return deduplicate(values);
    if (!data.next_cursor || data.next_cursor === cursor) throw new Error('Notion pagination could not continue. The previous feed was kept.');
    cursor = data.next_cursor;
  }
  throw new Error('Calendar exceeded the pagination limit. The previous feed was kept.');
}
export async function main() {
  const token = (process.env.NOTION_TOKEN || '').trim();
  const hexKey = (process.env.BIRTHDAY_WIDGET_KEY || '').trim();
  if (!token) throw new Error('Add the NOTION_TOKEN repository secret first.');
  if (!/^[0-9a-f]{64}$/i.test(hexKey)) throw new Error('BIRTHDAY_WIDGET_KEY must be the 64-character key generated by Start Here.');
  const key = Buffer.from(hexKey, 'hex');
  const birthdays = await queryBirthdays(token);
  let previous;
  try { previous = decrypt(JSON.parse(await readFile(OUTPUT, 'utf8')), key); }
  catch (error) {
    if (error.code !== 'ENOENT') console.log('Creating a refreshed encrypted feed.');
  }
  if (previous && JSON.stringify(previous.birthdays) === JSON.stringify(birthdays)) {
    console.log('No birthday changes. The existing encrypted feed remains current.');
    return;
  }
  await mkdir(new URL('.', OUTPUT), {recursive:true});
  await writeFile(OUTPUT, JSON.stringify(encrypt({birthdays}, key), null, 2) + '\n');
  console.log('Encrypted birthday feed updated.');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
